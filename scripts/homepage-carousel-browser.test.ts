import assert from "node:assert/strict";
import { Pool } from "pg";
import { request, chromium, expect } from "@playwright/test";
import chromiumBinary from "@sparticuz/chromium";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { brotliDecompressSync } from "node:zlib";
import { execFileSync } from "node:child_process";
import { resolve } from "node:path";
import sharp from "sharp";
import { DEFAULT_CAROUSEL, type CarouselSlide } from "../src/lib/homepage-carousel";
async function main() {
  if (!process.env.DATABASE_URL || new URL(process.env.DATABASE_URL).pathname !== "/inventory_test") throw new Error("Only isolated inventory_test is supported.");
  const base = process.env.TEST_BASE_URL || "http://127.0.0.1:3000";
  const pool = new Pool({ connectionString: process.env.DATABASE_URL });
  const old = (await pool.query("SELECT value FROM store_meta WHERE key='homepage.carousel.v1'")).rows[0];
  const other = (await pool.query("SELECT key,value FROM store_meta WHERE key IN ('store.settings.v1','pricing.settings') ORDER BY key")).rows;
  const owner = await request.newContext({ baseURL: base }), guest = await request.newContext({ baseURL: base });
  let browser;
  const json = async (r: Awaited<ReturnType<typeof owner.get>>) => { const data = await r.json() as { slides: CarouselSlide[]; image: string }; assert.ok(r.ok(), JSON.stringify(data)); return data; };
  try {
    assert.equal((await guest.get("/api/homepage-carousel")).status(), 401);
    assert.equal((await guest.put("/api/homepage-carousel", { data: { slides: DEFAULT_CAROUSEL } })).status(), 401);
    assert.equal((await guest.post("/api/carousel-images", { data: "bad" })).status(), 401);
    await json(await owner.post("/api/owner", { data: { password: process.env.TEST_ADMIN_PASSWORD || "inventory-test-only" } }));
    assert.equal((await owner.put("/api/homepage-carousel", { headers: { origin: "https://evil.invalid" }, data: { slides: DEFAULT_CAROUSEL } })).status(), 400);
    assert.equal((await owner.post("/api/carousel-images", { headers: { origin: "https://evil.invalid", "content-type": "image/png" }, data: "bad" })).status(), 400);
    assert.equal((await owner.post("/api/carousel-images", { headers: { "content-type": "image/svg+xml" }, data: "<svg/>" })).status(), 400);
    assert.equal((await owner.post("/api/carousel-images", { headers: { "content-type": "image/png" }, data: "not an image" })).status(), 400);
    assert.equal((await owner.post("/api/carousel-images", { headers: { "content-type": "image/png" }, data: Buffer.alloc(8 * 1024 * 1024 + 1) })).status(), 413);
    const png = await sharp({ create: { width: 1600, height: 800, channels: 3, background: "#293c56" } }).png().toBuffer();
    const uploaded = await json(await owner.post("/api/carousel-images", { headers: { "content-type": "image/png" }, data: png }));
    const image = await guest.get(uploaded.image);
    assert.equal(image.status(), 200); assert.equal(image.headers()["content-type"], "image/webp");
    assert.equal((await sharp(await image.body()).metadata()).format, "webp");
    const slides = DEFAULT_CAROUSEL.map(slide => ({ ...slide }));
    slides[0].title = "Carousel API test"; slides[0].image = uploaded.image;
    slides[1].enabled = false; slides[1].title = "SECRET HIDDEN TEST PROMOTION";
    await json(await owner.put("/api/homepage-carousel", { data: { slides } }));
    assert.ok(!(await (await guest.get("/")).text()).includes("SECRET HIDDEN TEST PROMOTION"));
    assert.equal((await json(await owner.get("/api/homepage-carousel"))).slides[1].enabled, false);
    for (const bad of [[], slides.map(slide => ({ ...slide, enabled: false })), [{ ...slides[0], href: "javascript:alert(1)" }], [{ ...slides[0], image: "/api/carousel-images/11111111-1111-1111-1111-111111111111.webp" }]]) assert.equal((await owner.put("/api/homepage-carousel", { data: { slides: bad } })).status(), 400);
    await mkdir("artifacts/chromium-libs", { recursive: true });
    await writeFile("artifacts/al2023.tar", brotliDecompressSync(await readFile("node_modules/@sparticuz/chromium/bin/al2023.tar.br")));
    execFileSync("tar", ["-xf", "artifacts/al2023.tar", "-C", "artifacts/chromium-libs"]);
    browser = await chromium.launch({ executablePath: await chromiumBinary.executablePath(), args: chromiumBinary.args, env: { ...process.env, LD_LIBRARY_PATH: `${resolve("artifacts/chromium-libs/lib")}:${process.env.LD_LIBRARY_PATH || ""}` }, headless: true });
    const context = await browser.newContext({ viewport: { width: 1550, height: 1100 } });
    await context.addCookies((await owner.storageState()).cookies);
    const page = await context.newPage(), errors: string[] = [];
    page.on("pageerror", error => errors.push(error.message));
    await page.goto(base + "/admin", { waitUntil: "networkidle" });
    await page.getByRole("button", { name: "Homepage carousel", exact: true }).click();
    await expect(page.getByLabel("Slide title", { exact: true })).toHaveValue("Carousel API test");
    await page.getByLabel("Slide title", { exact: true }).fill("GUI promotion\nMade by the owner");
    await page.getByLabel("Upload image", { exact: true }).setInputFiles({ name: "banner.png", mimeType: "image/png", buffer: png });
    await expect(page.getByRole("status")).toContainText("Image uploaded");
    await expect(page.locator(".carousel-preview h1")).toContainText("GUI promotion");
    assert.equal((await json(await owner.get("/api/homepage-carousel"))).slides[0].title, "Carousel API test", "Draft must not publish early");
    await page.getByRole("button", { name: "Move slide 1 down", exact: true }).click();
    await page.getByRole("button", { name: "Save carousel", exact: true }).click();
    await expect(page.getByRole("status")).toContainText("Carousel saved");
    const persisted = (await json(await owner.get("/api/homepage-carousel"))).slides;
    assert.equal(persisted[0].enabled, false); assert.equal(persisted[1].title, "GUI promotion\nMade by the owner");
    assert.notEqual(persisted[1].image, uploaded.image);
    await page.getByRole("button", { name: "Add slide", exact: true }).click();
    await page.getByLabel("Slide title", { exact: true }).fill("Unsaved throwaway");
    await page.getByRole("button", { name: "Discard changes", exact: true }).click();
    await expect(page.locator(".carousel-slide-row")).toHaveCount(3);
    await page.getByRole("button", { name: "Remove slide 3", exact: true }).click();
    await expect(page.locator(".carousel-slide-row")).toHaveCount(2);
    await page.getByRole("button", { name: "Discard changes", exact: true }).click();
    await page.screenshot({ path: "artifacts/carousel-editor-desktop.png", fullPage: true, animations: "disabled" });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: "artifacts/carousel-editor-mobile.png", fullPage: true, animations: "disabled" });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "Admin mobile overflow");
    await page.reload({ waitUntil: "networkidle" });
    await page.getByRole("button", { name: "Homepage carousel", exact: true }).click();
    await expect(page.locator(".carousel-slide-row").nth(1)).toContainText("GUI promotion");
    await page.goto(base, { waitUntil: "networkidle" });
    await expect(page.locator(".hero h1")).toContainText("GUI promotion");
    await expect(page.getByRole("button", { name: /^View promotion/ })).toHaveCount(2);
    await page.getByRole("button", { name: "Next promotion", exact: true }).click();
    await expect(page.locator(".hero h1")).toContainText("More power.");
    await page.getByRole("button", { name: "Previous promotion", exact: true }).click();
    await expect(page.locator(".hero h1")).toContainText("GUI promotion");
    await page.screenshot({ path: "artifacts/carousel-homepage-mobile.png", fullPage: true, animations: "disabled" });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "Homepage mobile overflow");
    await json(await owner.put("/api/homepage-carousel", { data: { slides: [persisted[1]] } }));
    await page.reload({ waitUntil: "networkidle" });
    await expect(page.getByRole("button", { name: "Next promotion", exact: true })).toHaveCount(0);
    assert.equal((await guest.get(persisted[1].image)).status(), 200);
    const dozen = Array.from({ length: 12 }, (_, i) => ({ ...persisted[1], id: `max-slide-${i}`, title: i === 0 ? "A long promotional heading with words and details that must remain readable on a small screen" : `Promotion ${i + 1}`, description: "Longer descriptive copy for the owner to explain a promotion. ".repeat(5), enabled: true }));
    await json(await owner.put("/api/homepage-carousel", { data: { slides: dozen } }));
    await page.reload({ waitUntil: "networkidle" });
    await expect(page.getByRole("button", { name: /^View promotion/ })).toHaveCount(12);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "Twelve-slide mobile overflow");
    const heroBox = await page.locator(".hero").boundingBox(), titleBox = await page.locator(".hero h1").boundingBox();
    assert.ok(heroBox && titleBox && titleBox.y + titleBox.height < heroBox.y + heroBox.height, "Long title clipped");
    assert.deepEqual((await pool.query("SELECT key,value FROM store_meta WHERE key IN ('store.settings.v1','pricing.settings') ORDER BY key")).rows, other);
    assert.deepEqual(errors, []);
    console.log("PASS: owner and CSRF protection, image decode/size/type checks, public immutable WebP serving, hidden slide privacy, missing-image rejection, GUI upload/edit/reorder/add/remove/discard/save/reload, draft isolation, manual next/previous navigation, single-slide controls, desktop/mobile without overflow or page errors; store/pricing settings unchanged.");
  } finally {
    await browser?.close();
    if (old) await pool.query("INSERT INTO store_meta(key,value) VALUES('homepage.carousel.v1',$1) ON CONFLICT(key) DO UPDATE SET value=EXCLUDED.value", [old.value]);
    else await pool.query("DELETE FROM store_meta WHERE key='homepage.carousel.v1'");
    await owner.dispose(); await guest.dispose(); await pool.end();
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
